# Prepares gitignored temporary secrets for local deploy Compose smoke tests.
# Does NOT weaken production validators. Output: secrets/deploy-smoke/ (gitignored).
# Usage (repo root): .\scripts\prepare-deploy-smoke-secrets.ps1

$ErrorActionPreference = "Stop"
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$outDir = Join-Path $root "secrets\deploy-smoke"
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

. (Join-Path $PSScriptRoot "set-java-home.ps1") | Out-Null

$privatePath = Join-Path $outDir "jwt-private.pem"
$publicPath = Join-Path $outDir "jwt-public.pem"
if (-not ((Test-Path $privatePath) -and (Test-Path $publicPath))) {
	$code = @'
import java.nio.file.*;
import java.security.*;
import java.util.Base64;
public class GenDeploySmokeJwt {
  public static void main(String[] a) throws Exception {
    KeyPairGenerator g = KeyPairGenerator.getInstance("RSA");
    g.initialize(2048);
    KeyPair kp = g.generateKeyPair();
    write(a[0], "PRIVATE KEY", kp.getPrivate().getEncoded());
    write(a[1], "PUBLIC KEY", kp.getPublic().getEncoded());
  }
  static void write(String path, String type, byte[] der) throws Exception {
    String b64 = Base64.getMimeEncoder(64, new byte[]{'\n'}).encodeToString(der);
    Files.writeString(Path.of(path), "-----BEGIN "+type+"-----\n"+b64+"\n-----END "+type+"-----\n");
  }
}
'@
	$tmp = Join-Path $env:TEMP "payflow-deploy-smoke-jwt"
	New-Item -ItemType Directory -Force -Path $tmp | Out-Null
	$setPath = Join-Path $tmp "GenDeploySmokeJwt.java"
	Set-Content -Path $setPath -Value $code -Encoding ASCII
	Push-Location $tmp
	try {
		& javac GenDeploySmokeJwt.java
		& java GenDeploySmokeJwt $privatePath $publicPath
	}
	finally {
		Pop-Location
	}
}

# Cryptographically random values - never commit; never log values.
$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
function Get-RandomBase64([int]$byteCount) {
	$bytes = New-Object byte[] $byteCount
	$rng.GetBytes($bytes)
	return [Convert]::ToBase64String($bytes)
}

$dbPassword = "DeploySmokeDb_" + (Get-RandomBase64 24).Replace("=", "").Replace("+", "x").Replace("/", "y")
$pepper = "DeploySmokePepper_" + (Get-RandomBase64 24).Replace("=", "").Replace("+", "x").Replace("/", "y")
$webhookKey = Get-RandomBase64 32

# Absolute host paths — Compose resolves relative binds from the compose file directory.
$privateAbs = (Resolve-Path $privatePath).Path
$publicAbs = (Resolve-Path $publicPath).Path

$envPath = Join-Path $outDir ".env"
@(
	"# Generated by scripts/prepare-deploy-smoke-secrets.ps1 - gitignored; temporary smoke only."
	"POSTGRES_DB=payflow"
	"POSTGRES_USER=payflow"
	"POSTGRES_PASSWORD=$dbPassword"
	"REDIS_PASSWORD="
	"API_KEY_HASH_PEPPER=$pepper"
	"WEBHOOK_SECRET_ENCRYPTION_KEY=$webhookKey"
	"PAYFLOW_CORS_ALLOWED_ORIGINS=https://app.example.com"
	"PAYFLOW_JWT_PRIVATE_KEY_FILE=$privateAbs"
	"PAYFLOW_JWT_PUBLIC_KEY_FILE=$publicAbs"
	"PAYFLOW_DEPLOY_HTTP_PORT=18080"
	"PAYFLOW_KAFKA_ENABLED=false"
	"PAYFLOW_KAFKA_CONSUMER_ENABLED=false"
	"PAYFLOW_OUTBOX_PUBLISHER_ENABLED=false"
	"PAYFLOW_WEBHOOK_DELIVERY_ENABLED=false"
) | Set-Content -Path $envPath -Encoding UTF8

Write-Host "Wrote smoke secrets under secrets/deploy-smoke/ (gitignored)."
Write-Host "Next: docker compose -f infra/docker-compose.deploy.yml --env-file secrets/deploy-smoke/.env up -d --build"
