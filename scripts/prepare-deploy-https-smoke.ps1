# Prepares gitignored secrets + local TLS material for HTTPS deploy Compose smoke (Task 9.2).
# Output: secrets/deploy-https/.env (+ JWT PEMs) and secrets/local-https/ (TLS).
# Does NOT weaken ProductionSecurityValidator. CORS stays non-localhost (same-origin Nginx).
#
# Usage (repo root): .\scripts\prepare-deploy-https-smoke.ps1

$ErrorActionPreference = "Stop"
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$outDir = Join-Path $root "secrets\deploy-https"
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

& (Join-Path $PSScriptRoot "prepare-local-https-certs.ps1")

. (Join-Path $PSScriptRoot "set-java-home.ps1") | Out-Null

$privatePath = Join-Path $outDir "jwt-private.pem"
$publicPath = Join-Path $outDir "jwt-public.pem"
if (-not ((Test-Path $privatePath) -and (Test-Path $publicPath))) {
	$code = @'
import java.nio.file.*;
import java.security.*;
import java.util.Base64;
public class GenDeployHttpsJwt {
  public static void main(String[] a) throws Exception {
    KeyPairGenerator g = KeyPairGenerator.getInstance("RSA");
    g.initialize(2048);
    KeyPair kp = g.generateKeyPair();
    write(a[0], "PRIVATE KEY", kp.getPrivate().getEncoded());
    write(a[1], "PUBLIC KEY", kp.getPublic().getEncoded());
  }
  static void write(String path, String type, byte[] der) throws Exception {
    String b64 = Base64.getMimeEncoder(64, new byte[]{'\n'}).encodeToString(der);
    Files.writeString(Path.of(path), "-----BEGIN "+type+"-----\n"+b64+"\n-----END "+type+"-----\n");
  }
}
'@
	$tmp = Join-Path $env:TEMP "payflow-deploy-https-jwt"
	New-Item -ItemType Directory -Force -Path $tmp | Out-Null
	$setPath = Join-Path $tmp "GenDeployHttpsJwt.java"
	Set-Content -Path $setPath -Value $code -Encoding ASCII
	Push-Location $tmp
	try {
		& javac GenDeployHttpsJwt.java
		& java GenDeployHttpsJwt $privatePath $publicPath
	}
	finally {
		Pop-Location
	}
}

$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
function Get-RandomBase64([int]$byteCount) {
	$bytes = New-Object byte[] $byteCount
	$rng.GetBytes($bytes)
	return [Convert]::ToBase64String($bytes)
}

$dbPassword = "DeployHttpsDb_" + (Get-RandomBase64 24).Replace("=", "").Replace("+", "x").Replace("/", "y")
$pepper = "DeployHttpsPepper_" + (Get-RandomBase64 24).Replace("=", "").Replace("+", "x").Replace("/", "y")
$webhookKey = Get-RandomBase64 32

$privateAbs = (Resolve-Path $privatePath).Path
$publicAbs = (Resolve-Path $publicPath).Path
$tlsCertAbs = (Resolve-Path (Join-Path $root "secrets\local-https\tls.crt")).Path
$tlsKeyAbs = (Resolve-Path (Join-Path $root "secrets\local-https\tls.key")).Path

$httpsPort = "18443"
$httpPort = "18082"

$envPath = Join-Path $outDir ".env"
@(
	"# Generated by scripts/prepare-deploy-https-smoke.ps1 - gitignored; temporary HTTPS smoke only."
	"POSTGRES_DB=payflow"
	"POSTGRES_USER=payflow"
	"POSTGRES_PASSWORD=$dbPassword"
	"REDIS_PASSWORD="
	"API_KEY_HASH_PEPPER=$pepper"
	"WEBHOOK_SECRET_ENCRYPTION_KEY=$webhookKey"
	"# Prod validator forbids localhost CORS; SPA uses same-origin Nginx proxy."
	"PAYFLOW_CORS_ALLOWED_ORIGINS=https://app.example.com"
	"PAYFLOW_JWT_PRIVATE_KEY_FILE=$privateAbs"
	"PAYFLOW_JWT_PUBLIC_KEY_FILE=$publicAbs"
	"PAYFLOW_TLS_CERT_FILE=$tlsCertAbs"
	"PAYFLOW_TLS_KEY_FILE=$tlsKeyAbs"
	"PAYFLOW_DEPLOY_HTTP_PORT=$httpPort"
	"PAYFLOW_DEPLOY_HTTPS_PORT=$httpsPort"
	"PAYFLOW_KAFKA_ENABLED=false"
	"PAYFLOW_KAFKA_CONSUMER_ENABLED=false"
	"PAYFLOW_OUTBOX_PUBLISHER_ENABLED=false"
	"PAYFLOW_WEBHOOK_DELIVERY_ENABLED=false"
) | Set-Content -Path $envPath -Encoding UTF8

Write-Host "Wrote HTTPS smoke secrets under secrets/deploy-https/ (gitignored)."
Write-Host "Next:"
Write-Host "  docker compose -p payflow-deploy-https -f infra/docker-compose.deploy.yml -f infra/docker-compose.deploy.https.yml --env-file secrets/deploy-https/.env up -d --build"
Write-Host "Origin: https://127.0.0.1:$httpsPort  (self-signed; curl -k / Playwright ignoreHTTPSErrors)"
